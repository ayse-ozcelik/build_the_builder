"""The bank's test customers -> the table the mock Worker serves (src/data.js).

    python mock/build_data.py <test-customers.json>

The file of the case pack is taken as it is: every answer (status code, body, delay) is copied, nothing is
computed or invented here. Only the lookup is prepared: by customer number, by card number, by card and week.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BY_CUSTOMER = ("cards.list", "contact.email.get", "statement.pdf.send")
BY_CARD = ("cards.balance", "statement.week.get")
BY_CARD_AND_WEEK = ("statement.week.decide", "statement.week.change")


def leaf(entry):
    out = {"http": entry["http"], "response": entry["response"] if "response" in entry else entry["yanit"]}
    delay = entry.get("delaySeconds", entry.get("gecikmeSaniye"))
    if delay:
        out["delaySeconds"] = delay
    return out


def main(path):
    with open(path, encoding="utf-8") as f:
        customers = json.load(f)["customers"]
    table = {name: {} for name in BY_CUSTOMER + BY_CARD + BY_CARD_AND_WEEK}
    for customer in customers:
        number = str(customer["customerNo"]).strip()
        for name, entry in customer["services"].items():
            if name in BY_CUSTOMER:
                table[name][number] = leaf(entry)
            elif name in BY_CARD:
                for card, answer in entry.items():
                    if card in table[name]:
                        raise SystemExit("card %s appears twice in %s" % (card, name))
                    table[name][card] = leaf(answer)
            elif name in BY_CARD_AND_WEEK:
                for card, weeks in entry.items():
                    if card in table[name]:
                        raise SystemExit("card %s appears twice in %s" % (card, name))
                    table[name][card] = {str(week): leaf(answer) for week, answer in weeks.items()}
            else:
                raise SystemExit("unknown service %s for customer %s" % (name, number))
    os.makedirs(os.path.join(HERE, "src"), exist_ok=True)
    with open(os.path.join(HERE, "src", "data.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by mock/build_data.py from the case pack's test-customers.json. Do not edit.\n")
        f.write("export default " + json.dumps(table, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("customers: %d; answers: %s" % (len(customers), ", ".join(
        "%s %d" % (name, sum(len(v) if name in BY_CARD_AND_WEEK else 1 for v in rows.values())) for name, rows in table.items())))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
